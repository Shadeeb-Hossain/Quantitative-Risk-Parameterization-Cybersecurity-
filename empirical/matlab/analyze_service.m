function [service, f04] = analyze_service(dataDirectory, replay, parameters)
%ANALYZE_SERVICE Check the retained service outcomes and F04 figure inputs.
% Elias Calboreanu

cohorts = read_csv(fullfile(dataDirectory, 'primary_cohorts.csv'), ...
    {'kind', 'group', 'block_id', 'role', 'channel', 'phase'});
study = jsondecode(fileread(fullfile(dataDirectory, 'study_summary.json')));
assert(numel(cohorts.pass) == 199 && all(ismember(cohorts.pass, [0, 1])) && ...
    nnz(cohorts.pass) == 197 && nnz(cohorts.pass) == study.primary_cohorts_passed && ...
    numel(cohorts.pass) == study.primary_cohorts_assessed && study.study_complete && ...
    study.completed_trials == 36 && strcmp(study.status, 'NOT_PASSED'), ...
    'Expected the complete study with 197 passing cohorts out of 199.');
failed = csv_subset(cohorts, cohorts.pass == 0);
f02 = csv_subset(failed, strcmp(failed.block_id, 'f02'));
f04Cohort = csv_subset(failed, strcmp(failed.block_id, 'f04'));
assert(numel(f02.pass) == 1 && strcmp(f02.kind, 'logical') && strcmp(f02.group, 'full') && ...
    strcmp(f02.role, 'affected') && strcmp(f02.channel, 'new_tcp') && strcmp(f02.phase, 'full') && ...
    f02.complete && f02.newly_harmed == 1 && f02.failure_difference == -7, ...
    'Expected the whole-trial F02 cohort with one newly harmed matched request.');
assert(numel(f04Cohort.pass) == 1 && strcmp(f04Cohort.kind, 'logical') && strcmp(f04Cohort.group, 'guarded') && ...
    strcmp(f04Cohort.role, 'affected') && strcmp(f04Cohort.channel, 'continuity_new_tcp') && ...
    strcmp(f04Cohort.phase, 'guarded_admission') && f04Cohort.complete && ...
    f04Cohort.newly_harmed == 0 && f04Cohort.failure_difference == 0, ...
    'Expected the guarded F04 ordinary service latency cohort.');
f02Requests = read_csv(fullfile(dataDirectory, 'f02_matched_requests.csv'));
validateF02Cohort(f02Requests, f02);

events = read_csv(fullfile(dataDirectory, 'f04_events.csv'), {'event'});
time = @(name) eventTime(events, name);
loadStart = time('actual_load_start');
loadEnd = time('actual_load_end');
crossing = time('corrected_score_gate_first_crossing');
attempted = time('action_attempted');
installed = time('action_installed');
guardStart = time('guarded_admission_start');
guardEnd = time('guarded_admission_end');
ackStart = time('guarded_ack_grace_start');
ackEnd = time('guarded_ack_grace_end');
assert(loadStart < crossing && crossing <= attempted && attempted <= installed && ...
    installed < guardStart && guardStart < guardEnd && guardEnd < loadEnd && ...
    installed < ackStart && ackStart < ackEnd && ackEnd < loadEnd, ...
    'The F04 events are out of order.');

timeline = read_csv(fullfile(dataDirectory, 'f04_timeline.csv'));
[~, order] = sort(timeline.bin_index);
timeline = csv_subset(timeline, order);
liveFamily = [timeline.family_corrected_score_gate, timeline.family_score_only, ...
    timeline.family_count_rate, timeline.family_count_rate_gate, timeline.family_persistence];
liveScore = timeline.affected_E1;
assert(isequal(timeline.bin_index, (0:299).') && isequal(double(liveFamily), double(replay.family)) && ...
    isequal(timeline.affected_K1, replay.affected.K(:, 1)) && ...
    isequal(timeline.n, replay.affected.n) && ...
    isequal(timeline.affected_O15_1, replay.affected.O15(:, 1)) && ...
    isequal(double(timeline.affected_gate1), double(replay.affected.gate(:, 1))) && ...
    isequal(double(timeline.valid), double(replay.affected.valid)) && ...
    all(abs(liveScore - replay.affected.E(:, 1)) <= 1e-10 + 2e-12 * abs(liveScore)), ...
    'F04 decision trace and validated state replay disagree.');
first = find(replay.family(:, 1), 1);
assert(~isempty(first) && timeline.decision_offset_ns(first) == crossing && ...
    logical(timeline.affected_gate1(first)), 'The F04 first crossing differs from the live decision.');

requests = read_csv(fullfile(dataDirectory, 'f04_guarded_requests.csv'));
assert(numel(requests.seq) == 58 && numel(unique(requests.seq)) == 58 && ...
    all(requests.treated_attempt_count == 1 & requests.reference_attempt_count == 1 & ...
    requests.treated_success == 1 & requests.reference_success == 1 & ...
    requests.treated_intent_to_complete == 1 & requests.reference_intent_to_complete == 1 & ...
    requests.treated_not_dispatched == 0 & requests.reference_not_dispatched == 0) && ...
    all(requests.scheduled_offset_ns >= guardStart & requests.scheduled_offset_ns < guardEnd) && ...
    all(requests.treated_latency_ms > 0 & requests.reference_latency_ms > 0), ...
    'Expected the 58 matched single-attempt requests in the guarded F04 admission cohort.');
conditionalP95 = linearQuantile(requests.treated_latency_ms, 0.95);
observeP95 = linearQuantile(requests.reference_latency_ms, 0.95);
addedP95 = conditionalP95 - observeP95;
latencyLimit = f04Cohort.margin_ms;
assert(latencyLimit == 100 && addedP95 > latencyLimit && ...
    abs(addedP95 - f04Cohort.p95_delta_ms) <= 1e-9 && ...
    abs(conditionalP95 - f04Cohort.treated_p95_ms) <= 1e-9 && ...
    abs(observeP95 - f04Cohort.reference_p95_ms) <= 1e-9, ...
    'Recomputed F04 added p95 must exceed the limit and match the retained cohort.');

service = struct('study_status', study.status, 'primary_cohorts_passed', nnz(cohorts.pass), ...
    'primary_cohorts_assessed', numel(cohorts.pass), 'failed_cohorts', cohortRecords(failed), ...
    'f04_matched_successes', numel(requests.seq), 'f04_conditional_p95_ms', conditionalP95, ...
    'f04_observe_p95_ms', observeP95, 'f04_added_p95_ms', addedP95, ...
    'added_p95_limit_ms', latencyLimit);

f04.decision = struct('bin_index', timeline.bin_index, ...
    'decision_s_since_load_start', (timeline.decision_offset_ns - loadStart) / 1e9, ...
    'score', replay.affected.E(:, 1), ...
    'score_bound', repmat(parameters.state.policy.score_bounds(1), numel(timeline.bin_index), 1), ...
    'count', timeline.affected_K1, 'exposure_s', timeline.n, 'occupied_bins', timeline.affected_O15_1, ...
    'valid', timeline.valid, 'gate', timeline.affected_gate1, ...
    'score_gate_alarm', timeline.family_corrected_score_gate);
names = {'corrected_score_gate', 'score_only', 'count_rate', 'count_rate_gate', 'persistence'};
for r = 1:numel(names)
    firstIndex = find(replay.family(:, r), 1);
    assert(~isempty(firstIndex) && ...
        timeline.decision_offset_ns(firstIndex) == time([names{r}, '_first_crossing']), ...
        'F04 timing differs for %s.', names{r});
    f04.firstCrossingIndex.(names{r}) = firstIndex;
end
assert(f04.firstCrossingIndex.count_rate < f04.firstCrossingIndex.score_only && ...
    f04.firstCrossingIndex.score_only < f04.firstCrossingIndex.corrected_score_gate && ...
    f04.firstCrossingIndex.count_rate_gate == f04.firstCrossingIndex.corrected_score_gate && ...
    f04.firstCrossingIndex.persistence == f04.firstCrossingIndex.corrected_score_gate, ...
    'Expected the two earlier ungated crossings and the shared gated crossing in F04.');
f04.events = struct('event', {events.event}, 's_since_load_start', ...
    (events.trial_offset_ns - loadStart) / 1e9);
f04.latencies = struct('seq', requests.seq, 'scheduled_s_since_load_start', ...
    (requests.scheduled_offset_ns - loadStart) / 1e9, ...
    'conditional_proxy_ms', requests.treated_latency_ms, 'observe_ms', requests.reference_latency_ms);
end

function records = cohortRecords(cohorts)
fields = fieldnames(cohorts);
for i = 1:numel(cohorts.pass)
    for j = 1:numel(fields)
        column = cohorts.(fields{j});
        if iscell(column)
            records(i).(fields{j}) = column{i};
        else
            records(i).(fields{j}) = column(i);
        end
    end
end
end

function validateF02Cohort(requests, cohort)
assert(numel(requests.seq) == 543 && numel(requests.seq) == cohort.matched_ids && ...
    numel(unique(requests.seq)) == numel(requests.seq) && ...
    all(requests.treated_intent_to_complete == 1 & requests.reference_intent_to_complete == 1), ...
    'Expected all 543 matched intended requests in the F02 whole-trial cohort.');
treatedSuccess = requests.treated_success == 1;
referenceSuccess = requests.reference_success == 1;
assert(nnz(~treatedSuccess & referenceSuccess) == cohort.newly_harmed && ...
    nnz(treatedSuccess & referenceSuccess) == cohort.both_success && ...
    nnz(~treatedSuccess & ~referenceSuccess) == cohort.both_nonsuccess && ...
    nnz(treatedSuccess & ~referenceSuccess) == cohort.treated_success_reference_failure && ...
    nnz(~treatedSuccess) - nnz(~referenceSuccess) == cohort.failure_difference, ...
    'F02 paired outcomes differ from the reported cohort.');
treatedP95 = linearQuantile(requests.treated_latency_ms(treatedSuccess), 0.95);
referenceP95 = linearQuantile(requests.reference_latency_ms(referenceSuccess), 0.95);
assert(abs(treatedP95 - referenceP95 - cohort.p95_delta_ms) <= 1e-9, ...
    'F02 added p95 differs from the reported cohort.');
end

function offset = eventTime(events, name)
offset = events.trial_offset_ns(strcmp(events.event, name));
assert(isscalar(offset) && isfinite(offset), 'Expected one F04 event named %s.', name);
end

function value = linearQuantile(samples, probability)
samples = sort(samples);
rank = 1 + (numel(samples) - 1) * probability;
lower = floor(rank);
weight = rank - lower;
value = samples(lower) + weight * (samples(ceil(rank)) - samples(lower));
end
